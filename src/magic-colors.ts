export type MagicColorValueKind = 'rgb' | 'system';
export type MagicColorValue = {
    original: string;
    scssValue: string;
    kind: MagicColorValueKind;
    systemIndex?: number;
    systemName?: string;
};

export type MagicColorEntry = {
    index: number;
    name: string;
    rawForeground: string;
    rawBackground: string;
    foreground: MagicColorValue;
    background: MagicColorValue;
    transparentBackground: boolean;
    rawFlag1: string;
    rawFlag2: string;
};

